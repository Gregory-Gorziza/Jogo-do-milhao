def pad_levels(arrays):
    """Reserve 50 linhas por nível sem alterar a ordem dos dados cadastrados."""
    if any(len(array) != NIVEIS for array in arrays):
        raise ValueError(f"Cada array deve ter exatamente {NIVEIS} níveis.")
    for array in arrays:
        for level in array:
            if len(level) > PERGUNTAS_POR_NIVEL:
                raise ValueError(f"Um nível excede {PERGUNTAS_POR_NIVEL} perguntas.")
            level.extend([None] * (PERGUNTAS_POR_NIVEL - len(level)))


