def pad_levels(arrays):
    """Completa cada lista com None at? reservar 50 posi??es por n?vel."""
    if any(len(array) != NIVEIS for array in arrays):
        raise ValueError(f"Cada array deve ter exatamente {NIVEIS} n?veis.")
    for array in arrays:
        for level in array:
            if len(level) > PERGUNTAS_POR_NIVEL:
                raise ValueError(f"Um n?vel excede {PERGUNTAS_POR_NIVEL} perguntas.")
            level.extend([None] * (PERGUNTAS_POR_NIVEL - len(level)))


