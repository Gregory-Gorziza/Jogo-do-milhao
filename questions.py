def build_question_bank():
    """Valida as matrizes e combina os dados em perguntas para o jogo."""
    if any(len(array) != NIVEIS for _, array in QUESTION_ARRAYS):
        raise ValueError(f"Cada array deve ter exatamente {NIVEIS} n?veis.")

    bank = []
    for level in range(NIVEIS):
        for name, array in QUESTION_ARRAYS:
            if len(array[level]) != PERGUNTAS_POR_NIVEL:
                raise ValueError(
                    f"{name}, n?vel {level + 1}, deve ter "
                    f"{PERGUNTAS_POR_NIVEL} posi??es."
                )

        level_questions = []
        for row in range(PERGUNTAS_POR_NIVEL):
            values = [array[level][row] for _, array in QUESTION_ARRAYS]
            question, correct, wrong_1, wrong_2, wrong_3, hint = values
            if all(value is None for value in values):
                continue

            location = f"n?vel {level + 1}, linha {row + 1}"
            answers = [correct, wrong_1, wrong_2, wrong_3]
            if not isinstance(question, str) or not question.strip():
                raise ValueError(f"Preencha PERGUNTAS em {location}.")
            for (name, _), answer in zip(QUESTION_ARRAYS[1:5], answers):
                if not isinstance(answer, str) or not answer.strip():
                    raise ValueError(f"Preencha {name} em {location}.")
            if len(set(answers)) != 4:
                raise ValueError(f"As quatro respostas devem ser diferentes em {location}.")
            if hint is not None and not isinstance(hint, str):
                raise ValueError(f"DICAS deve conter texto ou None em {location}.")

            level_questions.append(
                {
                    "id": f"nivel-{level + 1}-linha-{row + 1}",
                    "text": question.strip(),
                    "options": [answer.strip() for answer in answers],
                    "correct_index": 0,
                    "hint": hint.strip() if hint else "",
                }
            )
        bank.append(level_questions)
    return bank


